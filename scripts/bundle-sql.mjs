#!/usr/bin/env node
/**
 * Concatenates every migration, in order, into one file you can paste into the
 * Supabase SQL editor in a single go.
 *
 *   npm run sql:bundle
 *
 * Generated — never edit supabase/apply-all.sql by hand. Add a numbered file
 * to supabase/migrations/ and re-run this.
 */

import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const dir = new URL('../supabase/migrations/', import.meta.url).pathname;
const out = new URL('../supabase/apply-all.sql', import.meta.url).pathname;

const files = readdirSync(dir).filter((f) => f.endsWith('.sql')).sort();

const banner = (text) =>
  ['', '/' + '*'.repeat(74), ` * ${text}`, ' ' + '*'.repeat(73) + '/', ''].join('\n');

const body = files
  .map((f) => banner(f) + '\n' + readFileSync(join(dir, f), 'utf8').trimEnd() + '\n')
  .join('\n');

writeFileSync(
  out,
  `-- Domestic — all migrations, concatenated.
--
-- GENERATED by scripts/bundle-sql.mjs. Do not edit; add a numbered file under
-- supabase/migrations/ and re-run \`npm run sql:bundle\`.
--
-- Paste the whole thing into the Supabase SQL editor and hit Run. Every
-- statement is idempotent, so running this again is a no-op — you do not need
-- to track which migrations you have already applied.
--
-- Contains: ${files.join(', ')}
${body}`,
);

console.log(`supabase/apply-all.sql  ${files.length} migrations`);
for (const f of files) console.log(`  ${f}`);
